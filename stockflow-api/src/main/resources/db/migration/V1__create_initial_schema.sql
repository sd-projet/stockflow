
-- V1 : Schéma initial de StockFlow ERP

-- 1. Utilisateurs
CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'STOCK_MANAGER',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_app_users_role
        CHECK (role IN ('ADMIN', 'STOCK_MANAGER', 'MANAGER'))
);

CREATE UNIQUE INDEX uq_app_users_email
    ON app_users (LOWER(email));


-- 2. Catégories
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_categories_name
    ON categories (LOWER(name));


-- 3. Fournisseurs
CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(30),
    address VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 4. Produits
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    category_id BIGINT REFERENCES categories(id),
    quantity_in_stock INTEGER NOT NULL DEFAULT 0,
    minimum_stock INTEGER NOT NULL DEFAULT 0,
    unit VARCHAR(30) NOT NULL DEFAULT 'unité',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_products_stock
        CHECK (quantity_in_stock >= 0),
    CONSTRAINT chk_products_minimum_stock
        CHECK (minimum_stock >= 0)
);


-- 5. Association entre fournisseurs et produits
CREATE TABLE supplier_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    supplier_reference VARCHAR(100),
    unit_price NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_supplier_products
        UNIQUE (supplier_id, product_id),
    CONSTRAINT chk_supplier_products_price
        CHECK (unit_price >= 0)
);


-- 6. Commandes fournisseurs
CREATE TABLE purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(50) NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    order_date DATE,
    expected_delivery_date DATE,
    notes TEXT,
    created_by BIGINT NOT NULL REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_purchase_orders_status
        CHECK (status IN (
            'DRAFT',
            'ORDERED',
            'PARTIALLY_RECEIVED',
            'RECEIVED',
            'CANCELLED'
        )),
    CONSTRAINT chk_purchase_orders_dates
        CHECK (
            expected_delivery_date IS NULL
            OR order_date IS NULL
            OR expected_delivery_date >= order_date
        )
);


-- 7. Lignes de commande
CREATE TABLE purchase_order_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL
        REFERENCES purchase_orders(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity_ordered INTEGER NOT NULL,
    quantity_received INTEGER NOT NULL DEFAULT 0,
    unit_price NUMERIC(12, 2) NOT NULL,

    CONSTRAINT uq_purchase_order_product
        UNIQUE (purchase_order_id, product_id),
    CONSTRAINT chk_ordered_quantity
        CHECK (quantity_ordered > 0),
    CONSTRAINT chk_received_quantity
        CHECK (
            quantity_received >= 0
            AND quantity_received <= quantity_ordered
        ),
    CONSTRAINT chk_order_line_price
        CHECK (unit_price >= 0)
);


-- 8. Historique des mouvements de stock
CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    movement_type VARCHAR(20) NOT NULL,
    quantity_before INTEGER NOT NULL,
    quantity_after INTEGER NOT NULL,
    reason VARCHAR(500) NOT NULL,
    purchase_order_line_id BIGINT
        REFERENCES purchase_order_lines(id),
    performed_by BIGINT NOT NULL REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_stock_movement_type
        CHECK (movement_type IN ('IN', 'OUT', 'ADJUSTMENT')),
    CONSTRAINT chk_stock_movement_quantities
        CHECK (
            quantity_before >= 0
            AND quantity_after >= 0
        ),
    CONSTRAINT chk_stock_movement_change
        CHECK (
            (movement_type = 'IN'
                AND quantity_after > quantity_before)
            OR
            (movement_type = 'OUT'
                AND quantity_after < quantity_before)
            OR
            (movement_type = 'ADJUSTMENT'
                AND quantity_after <> quantity_before)
        )
);


-- Index pour accélérer les recherches courantes
CREATE INDEX idx_products_category
    ON products(category_id);

CREATE INDEX idx_purchase_orders_supplier
    ON purchase_orders(supplier_id);

CREATE INDEX idx_purchase_orders_status
    ON purchase_orders(status);

CREATE INDEX idx_order_lines_order
    ON purchase_order_lines(purchase_order_id);

CREATE INDEX idx_stock_movements_product_date
    ON stock_movements(product_id, created_at DESC);

CREATE INDEX idx_stock_movements_user
    ON stock_movements(performed_by);
