-- V7 : Clients et ventes (sorties de stock)

-- 1. Clients
CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    contact_name VARCHAR(100),
    email VARCHAR(255),
    phone VARCHAR(30),
    address VARCHAR(255),
    city VARCHAR(100),
    postal_code VARCHAR(20),
    country VARCHAR(100),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_customers_name
    ON customers (LOWER(name));


-- 2. Ventes
CREATE TABLE sales_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(50) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    order_date DATE,
    notes TEXT,
    created_by BIGINT NOT NULL REFERENCES app_users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_sales_orders_status
        CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED'))
);


-- 3. Lignes de vente
CREATE TABLE sales_order_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT NOT NULL REFERENCES sales_orders(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,

    CONSTRAINT uq_sales_order_product
        UNIQUE (sales_order_id, product_id),
    CONSTRAINT chk_sales_line_quantity
        CHECK (quantity > 0),
    CONSTRAINT chk_sales_line_price
        CHECK (unit_price >= 0)
);


-- 4. Compteur pour la numérotation (VTE-2026-0001)
CREATE TABLE sales_order_counters (
    year INTEGER PRIMARY KEY,
    last_number BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT chk_sales_counter_year
        CHECK (year BETWEEN 2000 AND 9999),
    CONSTRAINT chk_sales_counter_number
        CHECK (last_number >= 0)
);


-- 5. Lien entre un mouvement de stock et une ligne de vente
ALTER TABLE stock_movements
    ADD COLUMN sales_order_line_id BIGINT
        REFERENCES sales_order_lines(id);


-- Index
CREATE INDEX idx_sales_orders_customer
    ON sales_orders(customer_id);

CREATE INDEX idx_sales_orders_status
    ON sales_orders(status);

CREATE INDEX idx_sales_lines_order
    ON sales_order_lines(sales_order_id);

CREATE INDEX idx_stock_movements_sales_line
    ON stock_movements(sales_order_line_id);